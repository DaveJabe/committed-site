// Copies what the artwork needs from the app repository, so nothing is hand-copied:
//   - the palette tables (CommittedKit/Sources/CommittedKit/PaletteTokens.swift) → artwork/config/palettes.json
//   - the shipping app icons (iOS, macOS, watchOS asset catalogs) → artwork/brand/icons/
// Run after a palette or the icon changes:
//   node artwork/scripts/sync-from-app.mjs ../Committed
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = process.argv[2];
if (!appRoot) {
  console.error('usage: node artwork/scripts/sync-from-app.mjs <path to the Committed app repository>');
  process.exit(1);
}
const source = readFileSync(join(appRoot, 'CommittedKit/Sources/CommittedKit/PaletteTokens.swift'), 'utf8');

const order = [...source.matchAll(/^\s*case (\w+)(?: = "\w+")?$/gm)].map((m) => m[1]);
const labels = Object.fromEntries(
  [...source.matchAll(/case \.(\w+): return String\(localized: "([^"]+)"/g)].map((m) => [m[1], m[2]])
);

const hex = (r, g, b) => '#' + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('').toUpperCase();
function parseColor(expr) {
  let m = expr.match(/Color\(hex: "([0-9A-Fa-f]{6})"\)/);
  if (m) return { hex: '#' + m[1].toUpperCase(), alpha: 1 };
  m = expr.match(/red: (\d+) \/ 255, green: (\d+) \/ 255, blue: (\d+) \/ 255, opacity: ([\d.]+)/);
  if (m) return { hex: hex(+m[1], +m[2], +m[3]), alpha: +m[4] };
  throw new Error(`unparsed color: ${expr}`);
}
const css = ({ hex: h, alpha }) => {
  if (alpha === 1) return h;
  const n = parseInt(h.slice(1), 16);
  return `rgba(${n >> 16}, ${(n >> 8) & 255}, ${n & 255}, ${alpha})`;
};

const palettes = {};
for (const block of source.matchAll(/static let (\w+) = PaletteTokens\(([\s\S]*?)\n    \)/g)) {
  const [, id, body] = block;
  const tokens = {};
  for (const line of body.matchAll(/^\s*(\w+): (Color\(.*\)),?$/gm)) tokens[line[1]] = css(parseColor(line[2]));
  palettes[id] = { label: labels[id] ?? id, free: id === 'mint', ...tokens };
}

const ids = order.filter((id) => palettes[id]);
if (ids.length !== 8) throw new Error(`expected 8 palettes, found ${ids.length}: ${ids.join(', ')}`);
const out = {
  source: 'Committed/CommittedKit/Sources/CommittedKit/PaletteTokens.swift (generated by artwork/scripts/sync-from-app.mjs; do not edit by hand)',
  order: ids,
  palettes: Object.fromEntries(ids.map((id) => [id, palettes[id]])),
};
const target = join(dirname(fileURLToPath(import.meta.url)), '../config/palettes.json');
writeFileSync(target, JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${ids.length} palettes to ${target}`);

const catalog = join(appRoot, 'Committed/Resources/Assets.xcassets/AppIcon-Committed');
const icons = {
  'ios-1024.png': 'ios/AppIcon.appiconset/AppIcon-ios-marketing-1024-1x.png',
  'macos-1024.png': 'macos/AppIcon.appiconset/AppIcon-mac-512-2x.png',
  'watchos-1024.png': 'watchos/AppIcon.appiconset/AppIcon-watch-1024.png',
};
const iconDir = join(dirname(fileURLToPath(import.meta.url)), '../brand/icons');
mkdirSync(iconDir, { recursive: true });
for (const [name, path] of Object.entries(icons)) copyFileSync(join(catalog, path), join(iconDir, name));
console.log(`copied ${Object.keys(icons).length} app icons to ${iconDir}`);
